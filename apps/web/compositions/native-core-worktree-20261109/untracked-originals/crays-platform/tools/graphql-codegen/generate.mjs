import { readFile, writeFile } from "node:fs/promises";
import { fileURLToPath } from "node:url";
import { dirname, resolve } from "node:path";
import { buildASTSchema, concatAST, parse, validateSchema } from "graphql";
import { codegen } from "@graphql-codegen/core";
import * as typescript from "@graphql-codegen/typescript";
import * as typescriptResolvers from "@graphql-codegen/typescript-resolvers";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "../..");
const sources = [
  "src/graphql/schema.graphql",
  "src/graphql/oca-environment-records.graphql",
  "src/graphql/oca-environment-preflight.graphql",
];
const output = "src/graphql/generated/resolvers-types.ts";
const args = process.argv.slice(2);
if (args.some(arg => arg !== "--check") || args.length > 1) {
  throw new Error("Usage: node tools/graphql-codegen/generate.mjs [--check]");
}
// Read SDL only: importing schema.ts would construct server/runtime dependencies.
// Fail if the runtime assembly changes without the generator being updated.
const runtimeSource = await readFile(resolve(root, "src/graphql/schema.ts"), "utf8");
const runtimeSources = [...runtimeSource.matchAll(/readFileSync\(join\(process\.cwd\(\), "([^"\n]+\.graphql)"\), "utf8"\)/g)].map(match => match[1]);
if (JSON.stringify(runtimeSources) !== JSON.stringify(sources)) {
  throw new Error("GraphQL generator SDL sources differ from schema.ts runtime assembly");
}
const ast = concatAST(await Promise.all(sources.map(async path => parse(await readFile(resolve(root, path), "utf8")))));
const schema = buildASTSchema(ast);
const errors = validateSchema(schema);
if (errors.length) throw new AggregateError(errors, "Invalid composed Core GraphQL schema");
const generated = await codegen({
  filename: output,
  schema: ast,
  documents: [],
  plugins: [{ typescript: {} }, { typescriptResolvers: {} }],
  pluginMap: { typescript, typescriptResolvers },
  config: {
    contextType: "../context#CraysGraphQLContext",
    useTypeImports: true,
  },
});
const expected = "// Generated by npm run graphql:generate. Do not edit.\n" + generated;
if (args.includes("--check")) {
  if (await readFile(resolve(root, output), "utf8") !== expected) {
    throw new Error("Generated GraphQL resolver types are stale; run npm run graphql:generate");
  }
  console.log("Composed Core schema valid; generated resolver types match exactly.");
} else {
  await writeFile(resolve(root, output), expected);
  console.log(`Generated ${output} from ${sources.length} runtime SDL sources.`);
}
