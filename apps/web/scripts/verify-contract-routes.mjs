const forbiddenKeys = [
  "secret",
  "secrets",
  "token",
  "tokens",
  "credential",
  "credentials",
  "privateKey",
  "private_key",
  "privateKeys",
  "private_keys",
  "nsec",
];

function getByPath(value, path) {
  return path.split(".").reduce((current, segment) => {
    if (current === null || current === undefined) return undefined;
    return current[segment];
  }, value);
}

function collectForbiddenKeyPaths(value, currentPath = "$") {
  if (!value || typeof value !== "object") return [];
  if (Array.isArray(value)) {
    return value.flatMap((item, index) => collectForbiddenKeyPaths(item, `${currentPath}[${index}]`));
  }

  return Object.entries(value).flatMap(([key, nested]) => {
    const normalized = key.toLowerCase();
    const ownPath = `${currentPath}.${key}`;
    const matches = forbiddenKeys.some((forbidden) => normalized.includes(forbidden.toLowerCase())) ? [{ path: ownPath, value: nested }] : [];
    return [...matches, ...collectForbiddenKeyPaths(nested, ownPath)];
  });
}

async function verifyRoute(route) {
  const url = new URL(route.path, baseUrl);
  const response = await fetch(url, {
    method: route.method ?? "GET",
    headers: route.body ? { "content-type": "application/json" } : undefined,
    body: route.body ? JSON.stringify(route.body) : undefined,
  });
  const text = await response.text();
  let json;

  try {
    json = JSON.parse(text);
  } catch {
    throw new Error(`${route.path} did not return JSON.`);
  }

  const expectedStatus = route.expectedStatus ?? 200;
  if (response.status !== expectedStatus) {
    throw new Error(`${route.path} returned HTTP ${response.status}, expected ${expectedStatus}.`);
  }

  for (const [path, expectedValue] of Object.entries(route.expected)) {
    const actualValue = getByPath(json, path);
    if (actualValue !== expectedValue) {
      throw new Error(`${route.path} expected ${path}=${JSON.stringify(expectedValue)}, got ${JSON.stringify(actualValue)}.`);
    }
  }

  const forbiddenPaths = collectForbiddenKeyPaths(json);
  const suspiciousPaths = forbiddenPaths.filter((entry) => entry.value !== false);

  if (suspiciousPaths.length > 0) {
    throw new Error(`${route.path} returned forbidden-looking key paths: ${suspiciousPaths.map((entry) => entry.path).join(", ")}`);
  }

  return {
    path: route.path,
    status: response.status,
    checkedExpectations: Object.keys(route.expected).length,
  };
}

const routesToCheck = [...contractRoutes, ...writeGuardRoutes];
const results = [];
const failures = [];

for (const route of routesToCheck) {
  try {
    results.push(await verifyRoute(route));
  } catch (error) {
    failures.push({
      path: route.path,
      error: error instanceof Error ? error.message : String(error),
    });
  }
}

const summary = {
  baseUrl,
  checkedRoutes: routesToCheck.length,
  passedRoutes: results.length,
  failedRoutes: failures.length,
  results,
  failures,
};

console.log(JSON.stringify(summary, null, 2));

if (failures.length > 0) {
  process.exit(1);
}
