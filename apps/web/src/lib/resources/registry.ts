import type { PermissionKey, PermissionScope } from "@/lib/permissions";
import { resourceKeys, type ResourceDescriptor, type ResourceFieldDescriptor, type ResourceFilterOperator, type ResourceKey, type ResourceSourceSystem } from "@/lib/resources/types";

const idOperators: ResourceFilterOperator[] = ["eq", "in"];
const textOperators: ResourceFilterOperator[] = ["eq", "neq", "in", "contains", "startsWith", "isNull"];
const enumOperators: ResourceFilterOperator[] = ["eq", "neq", "in", "isNull"];
const dateOperators: ResourceFilterOperator[] = ["eq", "gt", "gte", "lt", "lte", "isNull"];
const numberOperators: ResourceFilterOperator[] = ["eq", "gt", "gte", "lt", "lte", "isNull"];

function field(input: {
  key: string;
  label: string;
  type?: ResourceFieldDescriptor["type"];
  sourceSystem: ResourceSourceSystem;
  nativeField?: string;
  requiresDiscovery?: boolean;
  nullable?: boolean;
  pii?: ResourceFieldDescriptor["pii"];
  public?: boolean;
  listVisible?: boolean;
  detailVisible?: boolean;
  clientSelectable?: boolean;
  filterOperators?: ResourceFilterOperator[];
  sortable?: boolean;
  readScopes?: PermissionScope[];
  readPermission?: PermissionKey;
  updatePermission?: PermissionKey;
}): ResourceFieldDescriptor {
  return {
    key: input.key,
    label: input.label,
    type: input.type ?? "text",
    nullable: input.nullable ?? false,
    pii: input.pii ?? "business",
    public: input.public ?? false,
    listVisible: input.listVisible ?? true,
    detailVisible: input.detailVisible ?? true,
    clientSelectable: input.clientSelectable ?? true,
    filterOperators: input.filterOperators ?? textOperators,
    sortable: input.sortable ?? false,
    readScopes: input.readScopes ?? ["organization"],
    readPermission: input.readPermission,
    updatePermission: input.updatePermission,
    source: {
      system: input.sourceSystem,
      nativeField: input.nativeField,
      requiresDiscovery: input.requiresDiscovery,
    },
  };
}

function descriptor(input: Omit<ResourceDescriptor, "cache" | "savedViews"> & Partial<Pick<ResourceDescriptor, "cache" | "savedViews">>): ResourceDescriptor {
  return {
    ...input,
    savedViews: input.savedViews ?? {
      enabled: true,
      shareScopes: ["private", "role"],
      maxColumns: 12,
    },
    cache: input.cache ?? {
      strategy: "session",
      tags: [`resource:${input.key}`],
    },
  };
}

