import type {AmbassadorRecruitmentDraft, RecruitmentInputPolicy} from "./ambassador-recruitment-draft-contract";

/** NEXT_DEPLOYMENT: ports into the existing SaaS onboarding, not another engine.
 * An anonymous original ingress can apply; personal status reads require the
 * original sender binding or a verified applicant identity. Neither grants an
 * Ambassador role. All actor/organisation/authority fields are server-derived. */
export type RecruitmentScope = Readonly<{
  purpose:"ambassador-recruitment";
  actorKind:"verified-applicant"|"original-anonymous-ingress";
  owningPrincipalRef:string;
  organizationId:string;
  authorityId:string;
  authorityVersion:number;
}>;
export type OriginalRecruitmentPolicy = Readonly<{
  originalId:string; version:number;
  privacyNoticeOriginalRef:string; privacyNoticeVersion:number;
  input:RecruitmentInputPolicy;
}>;
/** Store this reference before dispatch; never store draft PII in browser storage. */
export type RecruitmentAttemptReference = Readonly<{idempotencyKey:string;originalAttemptRef?:string}>;
export type RecruitmentPreparedDraft = Readonly<{
  draft:AmbassadorRecruitmentDraft;
  payloadSha256:string;
  policyOriginalId:string; policyVersion:number;
  privacyNoticeOriginalRef:string; privacyNoticeVersion:number;
}>;
export type OriginalRecruitmentEffect = Readonly<{
  organizationId:string; owningPrincipalRef:string;
  originalAttemptRef:string; idempotencyKey:string; payloadSha256:string;
  applicationOriginalRef:string; revision:number;
  originalInstitutionalTeamAssignmentRef:string;
  /** A received application is neither acceptance nor an operative account. */
  state:"received";
}>;
export type OriginalRecruitmentAttempt = Readonly<{
  organizationId:string; owningPrincipalRef:string;
  originalAttemptRef:string; idempotencyKey:string; revision:number;
  prepared:RecruitmentPreparedDraft;
  originalInputPolicy:OriginalRecruitmentPolicy;
  state:"prepared"|"dispatching"|"committed"|"not_committed";
  effect:OriginalRecruitmentEffect|null;
  originalAttemptPermanentlyFenced:boolean;
  originalFenceRef:string|null; originalFenceSha256:string|null;
}>;
export type OriginalRecruitmentPorts<Request> = Readonly<{
  /** Verified SDK applicant or original origin/CSRF/browser-bound public ingress.
   * A typed email, URL, public profile or client role is never an actor. */
  resolveCurrentScope(request:Request):Promise<RecruitmentScope|null>;
  /** Original server-issued opaque namespace; never an email/account-ID digest
   * generated by the browser. Rebind/claim across anonymous and signed-in actors
   * requires the original Core proof, not a matching contact email. */
  readOriginalJournalBinding(scope:RecruitmentScope):Promise<Readonly<{
    organizationId:string; owningPrincipalRef:string;
    opaqueNamespace:string; generation:number;
  }> | null>;
  readOriginalPolicy(scope:RecruitmentScope):Promise<OriginalRecruitmentPolicy|null>;
  /** Atomic durable private draft + original attempt keyed by original principal,
   * organisation and idempotency key. Changed payload under one key conflicts. */
  prepareOriginalAttempt(scope:RecruitmentScope,input:RecruitmentPreparedDraft,
    idempotencyKey:string):Promise<OriginalRecruitmentAttempt|"unknown_commit">;
  /** Own-only read by original key/ref. Null is NOT a negative commit proof.
   * The original private body and policy stay on the server during recovery. */
  readOriginalAttempt(scope:RecruitmentScope,ref:RecruitmentAttemptReference):Promise<OriginalRecruitmentAttempt|null>;
  /** Existing SaaS onboarding create. Native atomic expected-version/idempotency,
   * CURRENT original sender authority at commit under revocation locks, and the
   * genuine institutional assignment are required. No copied task/first staff. */
  createOriginalRecruitment(scope:RecruitmentScope,ref:Readonly<{
    originalAttemptRef:string; idempotencyKey:string; expectedAttemptRevision:number;
    payloadSha256:string;
  }>):Promise<OriginalRecruitmentEffect|"unknown_commit">;
  /** Independent original effect read; a response boolean is not a readback. */
  readOriginalEffect(scope:RecruitmentScope,ref:RecruitmentAttemptReference):Promise<OriginalRecruitmentEffect|null>;
}>;
export type RecruitmentBrowserResult =
  | Readonly<{status:"prepared";ref:RecruitmentAttemptReference}>
  | Readonly<{status:"unknown_commit";ref:RecruitmentAttemptReference}>
  | Readonly<{status:"not_committed";ref:RecruitmentAttemptReference;originalFenceRef:string;originalFenceSha256:string}>
  | Readonly<{status:"received";ref:RecruitmentAttemptReference;applicationOriginalRef:string;revision:number;
      ambassadorAdmitted:false;memberAccessGranted:false;paymentAuthorityGranted:false}>;

export type RecruitmentJournalBinding = Readonly<{opaqueNamespace:string;generation:number}>;
export type RecruitmentBrowserPolicy = Readonly<{
  policyOriginalId:string;policyVersion:number;
  privacyNoticeOriginalRef:string;privacyNoticeVersion:number;
  input:RecruitmentInputPolicy;journalBinding:RecruitmentJournalBinding;
}>;
export type RecruitmentBrowserCommandReference = RecruitmentAttemptReference & Readonly<{
  journalBinding:RecruitmentJournalBinding;
}>;
/** A BFF implements these against the original ports above. Every call resolves
 * the current original actor and compares the server journal binding. Changing
 * accounts cannot turn an earlier opaque key into the new user's application. */
export type RecruitmentBrowserCommands = Readonly<{
  readPolicy():Promise<RecruitmentBrowserPolicy>;
  prepare(input:Readonly<{
    draft:AmbassadorRecruitmentDraft;idempotencyKey:string;
    policyOriginalId:string;policyVersion:number;
    privacyNoticeOriginalRef:string;privacyNoticeVersion:number;
    journalBinding:RecruitmentJournalBinding;
  }>):Promise<RecruitmentBrowserResult>;
  execute(ref:RecruitmentBrowserCommandReference & Readonly<{originalAttemptRef:string}>):Promise<RecruitmentBrowserResult>;
  reconcile(ref:RecruitmentBrowserCommandReference):Promise<RecruitmentBrowserResult>;
}>;

